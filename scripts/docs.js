const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const read = (...p) => fs.readFileSync(path.join(root, ...p), 'utf8');

function loadData() {
  // 01-data.js is browser code: give it just enough of a browser to define its tables
  const noop = () => {};
  const ctx = {
    window: { Sungfluence: {} }, navigator: { platform: 'Win32', userAgent: '' },
    localStorage: { getItem: () => null, setItem: noop, removeItem: noop },
    document: { getElementById: () => null, createElement: () => ({}), documentElement: { setAttribute: noop, removeAttribute: noop } },
    console
  };
  vm.createContext(ctx);
  vm.runInContext(read('app', 'parts', '01-data.js') +
    '\n;globalThis.__d = { MODES, COMMON_DEFAULTS, FOCUS_CTL, EFFECT_CTL, COMMON_MORE, LETTER_CTL, LETTER_KEYS, COLOR_LABEL, RAMPS, FONT_OPTS };', ctx);
  // built-in plugins describe their own styles
  const plugins = [];
  ctx.Sungfluence = { plugin: (def) => plugins.push(def) };
  ctx.SungFluence = ctx.Sungfluence;
  for (const f of fs.readdirSync(path.join(root, 'app', 'plugins')).sort()) {
    if (!f.endsWith('.js') || /template/.test(f)) continue;
    vm.runInContext(read('app', 'plugins', f), ctx);
  }
  // the shortcut list, with Ctrl for the modifier key
  const sc = read('app', 'parts', '06-io.js').match(/const SHORTCUTS = (\[[\s\S]*?\n\]);/);
  const shortcuts = sc ? vm.runInNewContext(sc[1], { MOD: 'Ctrl' }) : [];
  return Object.assign(ctx.__d, { plugins, shortcuts });
}

const cell = (s) => String(s).replace(/\|/g, '\\|');
function describe(c, D) {
  if (c.type === 'range') return 'Slider, ' + c.min + ' to ' + c.max;
  if (c.type === 'toggle') return 'On or off';
  if (c.type === 'seg' || c.type === 'select' || c.type === 'choice') return (c.options || []).map((o) => (Array.isArray(o) ? o[1] : o)).join(', ');
  if (c.type === 'colormode') return c.options.map((o) => D.COLOR_LABEL[o] || o).join(', ');
  if (c.type === 'ramp') return Object.keys(D.RAMPS).concat('Custom').join(', ');
  if (c.type === 'text') return 'One line of text';
  if (c.type === 'textarea') return 'Text, several lines';
  if (c.type === 'ink') return 'A color';
  if (c.type === 'printon') return 'Dark paper with white letters, or light paper with black letters';
  if (c.type === 'font') return D.FONT_OPTS.map((o) => o[1]).join(', ');
  return '';
}
function shown(v, c, D) {
  if (v === undefined || v === null || v === '') return '';
  if (typeof v === 'boolean') return v ? 'On' : 'Off';
  if (c.type === 'colormode') return D.COLOR_LABEL[v] || v;
  const opts = c.options && c.options.find((o) => Array.isArray(o) && String(o[0]) === String(v));
  if (opts) return opts[1];
  if (c.key === 'font') { const f = D.FONT_OPTS.find((o) => o[0] === v); return f ? f[1] : v; }
  if (typeof v === 'string' && v.length > 40) return v.slice(0, 37).replace(/\n/g, ' ') + '...';
  return String(v).replace(/\n/g, ' / ');
}
function table(list, defaults, D) {
  const rows = list.filter((c) => c.key || c.type === 'font' || c.type === 'color').map((c) => {
    const key = c.key || (c.type === 'font' ? 'font' : 'color');
    const cc = c.type === 'color' ? { type: 'colormode', options: c.options || ['ink', 'image', 'tone', 'duotone'] } : c.type === 'font' ? { type: 'font', key: 'font' } : c;
    const label = c.label || (c.type === 'font' ? 'Typeface' : 'Color');
    return '| ' + cell(label) + ' | ' + cell(describe(cc, D)) + ' | ' + cell(shown(defaults[key], cc, D)) + ' |';
  });
  if (!rows.length) return '';
  return '| Setting | Choices | Starts at |\n| --- | --- | --- |\n' + rows.join('\n') + '\n';
}

function stylesPage(D) {
  const out = ['# Text art styles', '',
    '<!-- Generated by scripts/docs.js from the app\'s own style definitions. Do not edit by hand: change app/parts/01-data.js or the plugin, then run npm run build. -->', '',
    'Every style turns the photo, or your lines, into letters. Pick one under **Style** in the Text art panel. Its settings appear below the style tiles; the rarer ones are under **More controls**.', '',
    'All styles also share the settings in [Settings every style has](#settings-every-style-has) at the end of this page.', ''];
  for (const [key, M] of Object.entries(D.MODES)) {
    const defs = Object.assign({}, D.COMMON_DEFAULTS, M.defaults);
    out.push('## ' + M.name, '');
    if (M.about) out.push(M.about, '');
    out.push(table(M.controls, defs, D));
    if (M.more && M.more.length) out.push('**More controls**', '', table(M.more, defs, D));
    const letters = (D.LETTER_KEYS[key] || []).map((k) => D.LETTER_CTL[k].label);
    if (letters.length) out.push('**Letters:** ' + letters.join('; ') + '.', '');
  }
  out.push('## Extra effects', '', 'These styles come from plugins that ship with SungFluence. They appear under **Extra effects**, below the main styles. See [Plugins](plugins.md) to add more.', '');
  for (const p of D.plugins) {
    out.push('### ' + p.name, '');
    if (p.description) out.push(p.description, '');
    const defs = Object.assign({}, D.COMMON_DEFAULTS, p.defaults || {});
    const ctl = (p.controls || []);
    out.push(table(ctl.filter((c) => !c.more), defs, D));
    const more = ctl.filter((c) => c.more);
    if (more.length) out.push('**More controls**', '', table(more, defs, D));
  }
  out.push('## Settings every style has', '',
    'These sit in the closed sections under each style. Click a section name to open it.', '',
    '### Focus and fade', '',
    'Makes the letters fade toward an oval, a circle, a band across the picture, or a column. With the section open, the shape shows on the picture: drag the dot to move it, the square handles to change its size, width and softness, and the round handle to turn it. Hold Shift while turning to snap to 15 degree steps.', '',
    table(D.FOCUS_CTL, D.COMMON_DEFAULTS, D),
    '### Opacity, effects and inks', '', table(D.EFFECT_CTL, D.COMMON_DEFAULTS, D),
    'With **Limit to inks** on, the inks found in the picture appear as color chips. Click a chip to choose another color for that ink. **Use the found inks** puts them back.', '',
    '### Letters', '', 'Shown for styles that set real text.', '', table(Object.values(D.LETTER_CTL), Object.assign({}, D.COMMON_DEFAULTS, { weight: 700, tracking: 0 }), D),
    '### More controls', '', table(D.COMMON_MORE, D.COMMON_DEFAULTS, D));
  return out.join('\n').replace(/\n{3,}/g, '\n\n');
}
function shortcutsPage(D) {
  return ['# Keyboard shortcuts', '',
    '<!-- Generated by scripts/docs.js from the shortcut list in app/parts/06-io.js. Do not edit by hand. -->', '',
    'On a Mac, use Cmd where this page says Ctrl. Press **F1** at any time to open this help.', '',
    '| Keys | What they do |', '| --- | --- |',
    ...D.shortcuts.map(([k, t]) => '| ' + cell(k) + ' | ' + cell(t) + ' |'), ''].join('\n');
}

function writeDocs() {
  const D = loadData();
  const dir = path.join(root, 'docs', 'help');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'styles.md'), stylesPage(D));
  fs.writeFileSync(path.join(dir, 'shortcuts.md'), shortcutsPage(D));
  return D;
}
module.exports = { writeDocs };
if (require.main === module) { writeDocs(); console.log('docs/help/styles.md and shortcuts.md written'); }
