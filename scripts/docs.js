// Writes the parts of the help that come straight from the code, so they never drift from the app:
//   docs/help/styles.md     every style with its settings, ranges and defaults
//   docs/help/shortcuts.md  the keyboard shortcuts
// Runs as part of npm run build. Uses only Node's standard library.
