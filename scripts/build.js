// Builds the app from app/ into:
//   src/                  the desktop app, the web app on GitHub Pages, and what opens when you double-click src/index.html
//   single/sungfluence.html  one self-contained file, handy for quick tests and sharing. Only with --single.
// Edit files in app/, never in src/. Then run: npm run build
// Uses only Node's standard library.
// SPDX-License-Identifier: AGPL-3.0-or-later
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.join(__dirname, '..');
const A = (...p) => path.join(root, 'app', ...p);
const S = (...p) => path.join(root, 'src', ...p);
const read = (p) => fs.readFileSync(p, 'utf8');
const write = (p, s) => { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s); };
// String.replace treats $ in the replacement specially; code is full of $, so always pass a function
const put = (s, mark, value) => { if (!s.includes(mark)) throw new Error('missing ' + mark); return s.replace(mark, () => value); };

const pkg = JSON.parse(read(path.join(root, 'package.json')));
const NAME = pkg.productName || 'SungFluence';

// 1. the app: every file in app/parts, in name order, inside one function scope
const parts = fs.readdirSync(A('parts')).filter((f) => f.endsWith('.js')).sort();
const appJs = "(function () {\n'use strict';\n" + parts.map((f) => '/* ===== ' + f + ' ===== */\n' + read(A('parts', f))).join('\n') + '\n})();\n';

// 2. built-in plugins, and their source text for the "Get the template" button
const plugins = fs.readdirSync(A('plugins')).filter((f) => f.endsWith('.js')).sort();
const pluginSrc = Object.fromEntries(plugins.map((f) => [f, read(A('plugins', f))]));
// the template is a download for plugin authors, not a style of its own
const running = plugins.filter((f) => !/template/.test(f));

// 2b. help pages from docs/help, bundled so help works offline and ships with every installer.
//     styles.md and shortcuts.md are written from the code first, so they always match the app.
require('./docs.js').writeDocs();
const { md } = require('./md.js');
const HELP_ORDER = ['index', 'getting-started', 'workspace', 'photo', 'vector', 'text-art', 'styles', 'output-and-export', 'printing', 'urdu-and-arabic', 'plugins', 'shortcuts', 'troubleshooting'];
const helpDir = path.join(root, 'docs', 'help');
const helpIds = HELP_ORDER.concat(fs.readdirSync(helpDir).filter((f) => f.endsWith('.md')).map((f) => f.slice(0, -3)).filter((id) => !HELP_ORDER.includes(id)));
const help = { order: [], pages: {} };
for (const id of helpIds) {
  const file = path.join(helpDir, id + '.md');
  if (!fs.existsSync(file)) continue;
  const src = read(file).replace(/<!--[\s\S]*?-->/g, '');
  const title = (src.match(/^#\s+(.*)$/m) || [0, id])[1];
  // links to other help pages open inside the Help window; pictures come from help/img
  const html = md(src, (href, img) => (img ? 'help/' + href : /^[a-z0-9-]+\.md(#.*)?$/.test(href) ? '#help:' + href.replace('.md', '') : href));
  help.order.push(id);
  help.pages[id] = { title, html, text: src.replace(/[#*|`>[\]()]/g, ' ').replace(/\s+/g, ' ').toLowerCase() };
}
const helpImgs = fs.existsSync(path.join(helpDir, 'img')) ? fs.readdirSync(path.join(helpDir, 'img')).filter((f) => /\.(jpe?g|png)$/i.test(f)) : [];

// 3. sample images: "01-cat.jpg" becomes the sample "cat". Delete a file to remove a sample.
const MIME = { '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp' };
const samples = {};
for (const f of fs.readdirSync(A('samples')).sort()) {
  const ext = path.extname(f).toLowerCase();
  if (!MIME[ext]) continue;
  const key = f.replace(/^\d+[-_]/, '').replace(/\.[^.]+$/, '');
  samples[key] = 'data:' + MIME[ext] + ';base64,' + fs.readFileSync(A('samples', f)).toString('base64');
}
if (!samples.cat) throw new Error('app/samples needs a cat image: it is the first picture people see.');
const json = (o) => JSON.stringify(o).replace(/<\//g, '<\\/');

const css = read(A('styles.css'));
const body = read(A('body.html'));
const engine = read(A('engine.js'));
const banner = (what) => '/* ' + NAME + ' ' + pkg.version + ': ' + what + '. Generated by scripts/build.js from app/. Do not edit here.\n   Copyright (C) 2026 Ahmed Bilal. SPDX-License-Identifier: AGPL-3.0-or-later */\n';
const iconSvg = read(A('icon.svg'));

// ---------- src/ ----------
write(S('app.js'), banner('the app') + appJs);
write(S('engine.js'), banner('the engine') + engine);
fs.rmSync(S('plugins'), { recursive: true, force: true });
for (const f of plugins) write(S('plugins', f), pluginSrc[f]);
write(S('samples.js'), banner('sample images') + 'const SAMPLES = ' + json(samples) + ';\n');
fs.rmSync(S('help'), { recursive: true, force: true });
for (const f of helpImgs) { fs.mkdirSync(S('help', 'img'), { recursive: true }); fs.copyFileSync(path.join(helpDir, 'img', f), S('help', 'img', f)); }
write(S('help.js'), banner('help pages, from docs/help') + 'const HELP = ' + json(help) + ';\n');
write(S('plugin-files.js'), banner('plugin source for the template download') + 'const PLUGIN_FILES = ' + json(pluginSrc) + ';\n');
write(S('styles.css'), css);
write(S('icons', 'icon.svg'), iconSvg);
write(S('config.js'), "/* Local copies of the export libraries, so PDF and ZIP export work offline. */\nwindow.SUNGFLUENCE_VENDOR = { jspdf: 'vendor/jspdf.umd.min.js', jszip: 'vendor/jszip.min.js' };\nwindow.SUNGFLUENCE_VERSION = '" + pkg.version + "';\n");

const csp = "default-src 'self'; script-src 'self' blob:; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; font-src 'self' data:; connect-src 'self' data: blob:; worker-src 'self' blob:; object-src 'none'; base-uri 'none'";
const scripts = ['config.js', 'engine.js', ...running.map((f) => 'plugins/' + f), 'samples.js', 'plugin-files.js', 'help.js', 'app.js', 'pwa.js'];
const html = '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n' +
  '<meta http-equiv="Content-Security-Policy" content="' + csp + '">\n<title>' + NAME + '</title>\n' +
  '<meta name="description" content="' + pkg.description.replace(/"/g, '&quot;') + '">\n<meta name="theme-color" content="#141416">\n' +
  '<link rel="manifest" href="manifest.webmanifest">\n<link rel="icon" href="icons/icon.svg" type="image/svg+xml">\n<link rel="apple-touch-icon" href="icons/icon-192.png">\n' +
  '<link rel="stylesheet" href="fonts/fonts.css">\n<link rel="stylesheet" href="styles.css">\n</head>\n<body>\n' + body +
  scripts.map((f) => '<script src="' + f + '"></script>').join('\n') + '\n</body>\n</html>\n';
write(S('index.html'), html);

// offline cache list for the web version: every file in src/, with a version that changes when they change
const files = [];
(function walk(dir, rel) {
  for (const f of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, f), r = rel ? rel + '/' + f : f;
    if (fs.statSync(full).isDirectory()) walk(full, r);
    else if (r !== 'sw.js') files.push(r);
  }
})(S(), '');
const hash = crypto.createHash('sha1');
for (const f of files) hash.update(fs.readFileSync(S(f)));
write(S('sw.js'), '/* Offline cache for the web version. Generated by scripts/build.js. */\n' +
  "const CACHE = 'sungfluence-" + pkg.version + '-' + hash.digest('hex').slice(0, 8) + "';\n" +
  'const FILES = ' + JSON.stringify(['./', ...files], null, 1) + ';\n' +
  "self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });\n" +
  "self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });\n" +
  "self.addEventListener('fetch', (e) => { if (e.request.method !== 'GET') return; e.respondWith(caches.match(e.request).then((r) => r || fetch(e.request))); });\n");
console.log('src/ built: ' + parts.length + ' app parts, ' + plugins.length + ' plugins, ' + Object.keys(samples).length + ' samples');

// the single file has no folder next to it, so its help pictures go inside as data
function singleHelp() {
  const h = JSON.parse(JSON.stringify(help));
  for (const id of h.order) {
    h.pages[id].html = h.pages[id].html.replace(/src="help\/img\/([^"]+)"/g, (m, f) =>
      'src="data:image/' + (/png$/i.test(f) ? 'png' : 'jpeg') + ';base64,' + fs.readFileSync(path.join(helpDir, 'img', f)).toString('base64') + '"');
  }
  return h;
}

// ---------- single file ----------
if (process.argv.includes('--single')) {
  const fonts = 'https://fonts.googleapis.com/css2?family=Inter:wght@100..900&family=JetBrains+Mono:wght@400;500;700&family=Playfair+Display:wght@400..900&family=Oswald:wght@200..700&family=Noto+Naskh+Arabic:wght@400..700&family=Noto+Nastaliq+Urdu:wght@400..700&family=Special+Elite&display=swap';
  const single = '<title>' + NAME + '</title>\n<meta name="claude:viewport-fit-sides" content="cover">\n' +
    '<link rel="preconnect" href="https://fonts.googleapis.com">\n<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n' +
    '<link rel="stylesheet" href="' + fonts + '">\n<style>\n' + css + '</style>\n\n' + body.replace('icons/icon.svg', () => 'data:image/svg+xml;base64,' + Buffer.from(iconSvg).toString('base64')) + '\n' +
    '<script>\n' + engine + '\n</script>\n<script>\n' +
    running.map((f) => 'try {\n' + pluginSrc[f] + '\n} catch (e) { console.error("Built-in plugin failed: ' + f + '", e); }').join('\n') + '\n</script>\n' +
    '<script>\nconst SAMPLES = ' + json(samples) + ';\nconst PLUGIN_FILES = ' + json(pluginSrc) + ';\nconst HELP = ' + json(singleHelp()) + ';\n' + appJs + '</script>\n';
  write(path.join(root, 'single', 'sungfluence.html'), single);
  console.log('single/sungfluence.html built: ' + Math.round(single.length / 1024) + ' KB');
}
